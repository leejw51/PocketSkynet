//! Deterministic identity tiles.
//!
//! Why this lives in the client and not on the server: an avatar that is a pure
//! function of an identifier needs no storage, no upload, no moderation, and no
//! extra request — and it is *stable*, so a wallet you have seen before is
//! recognisable before you have read a single character of its address.
//!
//! Two outputs, both from one djb2 hash of the normalised seed:
//!
//! * [`monogram_for`] — the two characters drawn on the tile. For a wallet
//!   address they are the *leading two hex digits of the address itself*, so
//!   the tile can be checked against the `0x9f2a…` beside it rather than being
//!   an unrelated decoration. For anything else (room ids, which all begin
//!   `room_` and would otherwise every one of them read `RO`) they are two
//!   base-36 characters taken from the hash.
//! * [`hue_for`] — the tile colour, read from the *high* bits so it is
//!   decorrelated from the monogram: two accounts that collide on the letters
//!   almost never collide on the colour.
//!
//! Lightness and chroma are fixed in `app.css` (in OKLCH, so every hue lands on
//! the same perceptual lightness and the white monogram clears AA on all 360 of
//! them). The hue varies colour only, never legibility.

/// djb2 over UTF-16 code units, wrapping at 32 bits.
///
/// Bit-identical to the JavaScript original `((hash << 5) + hash + c) >>> 0`.
/// The `>>> 0` coerces to 32 bits every iteration, which is exactly what
/// `wrapping_mul`/`wrapping_add` on `u32` do; and `encode_utf16` reproduces the
/// JS iteration unit (a `String` in JS is a sequence of UTF-16 code units, not
/// scalar values). For hex addresses every unit is ASCII so the distinction is
/// moot — it matters only if this is ever fed a non-ASCII seed.
pub fn djb2(s: &str) -> u32 {
    s.encode_utf16()
        .fold(5381u32, |h, u| h.wrapping_mul(33).wrapping_add(u as u32))
}

/// Lowercase first, *then* strip `0x`, so an uppercase `0X…` prefix is also
/// removed and `0XAB…` and `0xab…` are one identity rather than two.
fn normalise(seed: &str) -> String {
    let lower = seed.to_ascii_lowercase();
    lower.strip_prefix("0x").unwrap_or(&lower).to_owned()
}

const BASE36: [u8; 36] = *b"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ";

/// The two characters drawn on an identity tile, uppercased.
///
/// Never panics and never returns an empty string: this is display code, and a
/// tile with nothing on it is indistinguishable from a rendering failure.
pub fn monogram_for(seed: &str) -> String {
    let s = normalise(seed);
    let head: Vec<char> = s.chars().take(2).collect();

    // A wallet address: show its own leading hex, so the tile and the address
    // beside it can be read as the same thing.
    if head.len() == 2 && s.len() >= 8 && s.chars().all(|c| c.is_ascii_hexdigit()) {
        return head.into_iter().flat_map(char::to_uppercase).collect();
    }

    // Everything else: two base-36 characters of the hash. 1 296 combinations,
    // taken from the low bits so they stay decorrelated from the hue.
    let h = djb2(&s);
    let a = BASE36[(h % 36) as usize] as char;
    let b = BASE36[((h / 36) % 36) as usize] as char;
    [a, b].into_iter().collect()
}

/// Tile hue (0..359).
///
/// Uses `>> 8` so the hue reads bits the monogram never touches.
pub fn hue_for(seed: &str) -> u16 {
    if seed.is_empty() {
        return 0;
    }
    ((djb2(&normalise(seed)) >> 8) % 360) as u16
}

